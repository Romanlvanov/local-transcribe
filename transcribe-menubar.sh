#!/bin/bash
# Иконка расшифровки в строке меню macOS (запуск/остановка веб-интерфейса, прогресс). Работает в фоне,
# терминал можно закрыть. Закрыть иконку - пункт «Выйти» в её меню.
DIR="$(cd "$(dirname "$0")" && pwd)"
mkdir -p "$DIR/output"
nohup "$DIR/.venv/bin/python" "$DIR/menubar.py" >>"$DIR/output/menubar.log" 2>&1 &
echo "Иконка запущена в строке меню (значок волны справа вверху)."
